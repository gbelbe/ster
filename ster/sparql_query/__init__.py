"""Public surface of ster.sparql_query, now split across submodules.

SPARQL query engine for ster: all query logic is isolated here so that the
TUI, CLI commands, and future AI-powered callers all share the same
entry-points.

Extension points
----------------
* *run_query* / *run_query_on_graph* -- pass any SPARQL string, including
  one generated by an AI, and receive a uniform ``QueryResult``.
* *PRESET_QUERIES* -- a registry of built-in queries; extend this list to
  add domain-specific or AI-suggested queries to the preset menu.
* *find_uri_column* -- heuristic to detect which result column contains
  concept URIs so the TUI can offer tree-navigation from results.

Every name that used to live directly in ster/sparql_query.py (including
the underscore-prefixed helpers several tests import or patch directly) is
re-exported here unchanged, so `from ster.sparql_query import X` /
`from ster import sparql_query; sparql_query.X` keeps working. See
docs/architecture/module-layout.md for the split rationale.
"""

