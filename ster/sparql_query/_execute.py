"""SPARQL execution against a loaded graph, and result-shaping helpers.

``run_query`` / ``run_query_on_graph`` are the primary entry-points shared by
the TUI, CLI, and MCP callers — pass any SPARQL string, including one
generated by an AI, and receive a uniform ``QueryResult``. ``find_uri_column``
and ``compute_col_widths`` support the results table view.
"""

from __future__ import annotations

import re
import time
from pathlib import Path
from typing import Any, Final

import rdflib

from ._caching import _SPARQL_LOCK, _trace, load_graph_cached
from ._types import QueryResult


def run_query(paths: list[Path], sparql_text: str) -> QueryResult:
    """Execute *sparql_text* against the taxonomy files at *paths*.

    Primary entry-point.  AI callers should generate a SPARQL string and
    pass it here — the result shape is always a ``QueryResult``.
    """
    if not sparql_text.strip():
        return QueryResult(columns=[], rows=[], error="Empty query.")
    try:
        t_load0 = time.time()
        g = load_graph_cached(paths)
        _trace(f"run_query load_graph_cached done in {time.time() - t_load0:.3f}s")
    except Exception as exc:
        return QueryResult(columns=[], rows=[], error=f"Load error: {exc}")
    t_exec0 = time.time()
    result = run_query_on_graph(g, sparql_text)
    _trace(f"run_query run_query_on_graph done in {time.time() - t_exec0:.3f}s")
    return result


def run_query_on_graph(g: rdflib.Graph, sparql_text: str) -> QueryResult:
    """Execute *sparql_text* against an already-loaded *g*.

    Separate from *run_query* so callers that maintain a cached or augmented
    graph (e.g. with a reasoner) can skip the file-load step.
    """
    try:
        t0 = time.time()
        with _SPARQL_LOCK:  # rdflib SPARQL parser is not thread-safe
            result = g.query(sparql_text)
        _trace(f"run_query_on_graph g.query() done in {time.time() - t0:.3f}s")
    except Exception as exc:
        return QueryResult(columns=[], rows=[], error=f"Query error: {exc}")

    qtype = _detect_query_type(sparql_text)

    if qtype == "ASK":
        return QueryResult(
            columns=["result"],
            rows=[["true" if bool(result) else "false"]],
            query_type="ASK",
        )

    if qtype in ("CONSTRUCT", "DESCRIBE"):
        g2 = getattr(result, "graph", None)
        ttl = g2.serialize(format="turtle") if g2 is not None else ""
        lines = [ln for ln in ttl.splitlines() if ln.strip()]
        return QueryResult(columns=["triple"], rows=[[ln] for ln in lines], query_type=qtype)

    # SELECT
    cols: list[str] = [str(v) for v in result.vars] if result.vars else []
    t_iter = time.time()
    rows: list[list[str]] = []
    for row in result:
        rows.append([_fmt_value(row[i]) for i in range(len(cols))])  # type: ignore[index]
    _trace(f"run_query_on_graph iteration done in {time.time() - t_iter:.3f}s ({len(rows)} rows)")
    return QueryResult(columns=cols, rows=rows, query_type=_LIT_SELECT)


_LIT_SELECT: Final = "SELECT"


def _oxigraph_result(raw: Any, qtype: str) -> QueryResult:
    """Normalise a pyoxigraph answer into the shape every caller already reads.

    *raw* is Any rather than object because pyoxigraph returns a different type
    per query form — a bool for ASK, an iterable of triples for CONSTRUCT, a
    QuerySolutions carrying .variables for SELECT — and the branch below is
    precisely the code that knows which. Typing it as object bought three
    type: ignore comments that said the same thing less clearly, and named the
    wrong error code while doing so.
    """
    if qtype == "ASK":
        return QueryResult(
            columns=["result"], rows=[["true" if bool(raw) else "false"]], query_type="ASK"
        )
    if qtype in ("CONSTRUCT", "DESCRIBE"):
        return QueryResult(columns=["triple"], rows=[[str(t)] for t in raw], query_type=qtype)
    cols = [str(v).lstrip("?") for v in raw.variables]
    rows = [[_fmt_oxigraph_term(row[i]) for i in range(len(cols))] for row in raw]
    return QueryResult(columns=cols, rows=rows, query_type=_LIT_SELECT)


def _fmt_oxigraph_term(term: object) -> str:
    """A cell as a plain string, matching what the rdflib path produces."""
    if term is None:
        return ""
    return getattr(term, "value", None) or str(term)


def run_query_on_taxonomy(
    taxonomy: object, sparql_text: str, timeout: float | None = None
) -> QueryResult:
    """Execute *sparql_text* against the session's model.

    The one entry point both transports use — ``POST /api/sparql_query`` and the MCP
    ``run_sparql`` tool — so neither holds query logic and neither can drift
    from the other.

    Oxigraph by default because it is ~10x faster on the map's own query and is
    already a core dependency; rdflib when the native engine is missing, which
    returns the same rows from the same graph, only slower. The choice is made
    here and nowhere else, so a caller never has to know which engine answered.

    With *timeout* (seconds) the query runs in a killable child process
    (:mod:`._sandbox`) and comes back ``timed_out`` past the deadline. Without
    it — the map, the TUI, the REST page — it runs in-process, as before. The
    rdflib fallback has no deadline: it is only reached without pyoxigraph.
    """
    if not sparql_text.strip():
        return QueryResult(columns=[], rows=[], error="Empty query.")

    from ..store import full_graph_oxigraph, full_graph_rdflib  # noqa: PLC0415

    store = full_graph_oxigraph(taxonomy)  # type: ignore[arg-type]
    if store is None:
        return run_query_on_graph(full_graph_rdflib(taxonomy), sparql_text)  # type: ignore[arg-type]
    if timeout is not None:
        from ._sandbox import run_with_timeout  # noqa: PLC0415

        try:
            return run_with_timeout(store, sparql_text, timeout)
        # No child process available (a locked-down host, or a spawn the platform
        # refuses with a ValueError): answering without a deadline beats not
        # answering, and the trace says it happened.
        except (OSError, RuntimeError, ValueError) as exc:
            _trace(f"sparql sandbox unavailable, running in-process: {exc}")
    try:
        t0 = time.time()
        raw = store.query(sparql_text)  # type: ignore[attr-defined]
        qtype = _detect_query_type(sparql_text)
        result = _oxigraph_result(raw, qtype)
        _trace(f"run_query_on_taxonomy oxigraph done in {time.time() - t0:.3f}s")
    # A malformed query is the caller's, not a server fault, so it comes back as
    # a QueryResult carrying the message rather than a 500.
    except Exception as exc:  # noqa: BLE001
        return QueryResult(columns=[], rows=[], error=f"Query error: {exc}")
    return result


def find_uri_column(result: QueryResult) -> int | None:
    """Return the index of the first column whose values look like concept URIs.

    Used by the TUI to offer direct tree-navigation from a result row.
    Returns ``None`` when no URI column is detected.
    """
    if not result.rows:
        return None
    for col_idx in range(len(result.columns)):
        sample = [row[col_idx] for row in result.rows[:10] if col_idx < len(row)]
        uri_hits = sum(
            1
            for v in sample
            if v.startswith(
                "http://"  # NOSONAR - scheme prefix, not a URL
            )
            or v.startswith("https://")
            or v.startswith("urn:")
        )
        if uri_hits >= max(1, len(sample) // 2):
            return col_idx
    return None


def compute_col_widths(columns: list[str], rows: list[list[str]], available: int) -> list[int]:
    """Compute column display widths to fill *available* characters.

    Each column gets at least 4 characters.  When all content fits within the
    available space the actual content widths are returned unchanged.  When the
    content is wider than the screen, widths are scaled down proportionally so
    no single column dominates.
    """
    n = len(columns)
    if n == 0:
        return []
    maxes: list[int] = [max(4, len(c)) for c in columns]
    for row in rows[:100]:
        for i, val in enumerate(row):
            if i < n:
                maxes[i] = max(maxes[i], len(val))
    sep = n - 1  # " │ " separators
    budget = max(n * 4, available - sep * 3)
    total_max = sum(maxes)
    if total_max <= budget:
        return maxes
    scale = budget / total_max
    widths = [max(4, int(m * scale)) for m in maxes]
    # absorb rounding error in the last column
    diff = budget - sum(widths)
    widths[-1] = max(4, widths[-1] + diff)
    return widths


def _fmt_value(val: object) -> str:
    if val is None:
        return ""
    if isinstance(val, rdflib.URIRef):
        return str(val)
    if isinstance(val, rdflib.Literal):
        lang = getattr(val, "language", None)
        return f"{val}@{lang}" if lang else str(val)
    return str(val)


def _detect_query_type(sparql_text: str) -> str:
    m = re.search(r"\b(SELECT|ASK|CONSTRUCT|DESCRIBE)\b", sparql_text, re.IGNORECASE)
    return m.group(1).upper() if m else "SELECT"
