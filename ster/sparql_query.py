def build_prefix_header(namespace_bindings: dict[str, str]) -> str:
    """Build a SPARQL PREFIX block from *namespace_bindings* only.

    Emits exactly the prefixes declared in the loaded TTL file, sorted
    alphabetically.  No standard prefixes are added automatically.
    """
    return (
        "\n".join(f"PREFIX {pfx}: <{uri}>" for pfx, uri in sorted(namespace_bindings.items()))
        + "\n\n"
    )


def build_qname_index(taxonomy: Taxonomy) -> dict[str, list[str]]:
    """Build a ``prefix → [local_name, ...]`` completion index.

    Includes local names extracted from every taxonomy node (classes, individuals,
    concepts, schemes, properties) plus well-known local names for all six standard
    prefixes.  Each list is deduplicated and sorted alphabetically.
    """
    ns_to_pfx: dict[str, str] = {uri: pfx for pfx, uri in taxonomy.namespace_bindings.items()}

    index: dict[str, list[str]] = {}
    seen: set[tuple[str, str]] = set()

    def _add_uri(uri: str) -> None:
        for ns, pfx in ns_to_pfx.items():
            if uri.startswith(ns):
                local = uri[len(ns) :]
                if local and (pfx, local) not in seen:
                    seen.add((pfx, local))
                    index.setdefault(pfx, []).append(local)
                return

    for uri in (
        *taxonomy.owl_classes,
        *taxonomy.owl_individuals,
        *taxonomy.concepts,
        *taxonomy.schemes,
        *taxonomy.owl_properties,
    ):
        _add_uri(uri)

    for pfx, qnames in _STANDARD_QNAMES.items():
        for local in qnames:
            if (pfx, local) not in seen:
                seen.add((pfx, local))
                index.setdefault(pfx, []).append(local)

    for pfx in index:
        index[pfx] = sorted(index[pfx])

    return index


def build_uri_index(taxonomy: Taxonomy) -> UriIndex:
    """Build a prefix → {all, classes, individuals} completion index.

    Each sub-list is sorted alphabetically.  Standard prefix well-known names
    are included under "all" and under "classes" where appropriate.
    """
    if TYPE_CHECKING:
        pass
    ns_to_pfx: dict[str, str] = {uri: pfx for pfx, uri in taxonomy.namespace_bindings.items()}

    # Collect per-bucket
    all_map: dict[str, list[str]] = {}
    cls_map: dict[str, list[str]] = {}
    ind_map: dict[str, list[str]] = {}
    seen_all: set[tuple[str, str]] = set()

    def _add(uri: str, bucket: dict[str, list[str]]) -> None:
        for ns, pfx in ns_to_pfx.items():
            if uri.startswith(ns):
                local = uri[len(ns) :]
                if local:
                    bucket.setdefault(pfx, []).append(local)
                    if (pfx, local) not in seen_all:
                        seen_all.add((pfx, local))
                        all_map.setdefault(pfx, []).append(local)
                return

    for uri in taxonomy.owl_classes:
        _add(uri, cls_map)
    for uri in taxonomy.owl_individuals:
        _add(uri, ind_map)
    for uri in (*taxonomy.concepts, *taxonomy.schemes, *taxonomy.owl_properties):
        _add(uri, all_map)

    # Standard well-known names: add owl:Class / rdfs:Class etc. to classes bucket
    _STANDARD_CLASS_LOCALS: dict[str, list[str]] = {
        "owl": ["Class", "NamedIndividual", "Thing", "Nothing"],
        "rdfs": ["Class", "Resource"],
        "rdf": ["Property"],
    }
    for pfx, qnames in _STANDARD_QNAMES.items():
        cls_locals = set(_STANDARD_CLASS_LOCALS.get(pfx, []))
        for local in qnames:
            if (pfx, local) not in seen_all:
                seen_all.add((pfx, local))
                all_map.setdefault(pfx, []).append(local)
            if local in cls_locals and local not in cls_map.get(pfx, []):
                cls_map.setdefault(pfx, []).append(local)

    idx: UriIndex = {}
    all_pfxs = set(all_map) | set(cls_map) | set(ind_map)
    for pfx in all_pfxs:
        idx[pfx] = {
            "all": sorted(set(all_map.get(pfx, []))),
            "classes": sorted(set(cls_map.get(pfx, []))),
            "individuals": sorted(set(ind_map.get(pfx, []))),
        }
    return idx


# SPARQL predicates that signal the object position expects a class URI
_CLASS_PREDICATES: frozenset[str] = frozenset(
    {
        "a",
        "rdf:type",
        "rdfs:subClassOf",
        "rdfs:domain",
        "rdfs:range",
        "owl:equivalentClass",
        "owl:disjointWith",
        "owl:unionOf",
        "owl:intersectionOf",
        "owl:complementOf",
    }
)

# Regex: last SPARQL token before the cursor (ignoring trailing whitespace)
_LAST_TOKEN_RE = re.compile(r"(\S+)\s+$")

# Regex: PREFIX name: declarations in a SPARQL buffer
_PREFIX_DECL_RE = re.compile(r"(?i)\bPREFIX\s+(\w+)\s*:")


def _sparql_context_at_cursor(buffer: str, pos: int) -> str:
    """Return ``"class"`` when the cursor is in a position expecting a class URI.

    Strips the in-progress token (e.g. ``"kai:"`` just typed) then looks at
    the immediately preceding whitespace-separated token.  Returns ``"any"``
    for all other positions.
    """
    before = buffer[:pos]
    # Remove the in-progress token (the prefix: or partial identifier being typed)
    stripped = re.sub(r"\S+$", "", before)
    m = _LAST_TOKEN_RE.search(stripped)
    if m and m.group(1) in _CLASS_PREDICATES:
        return "class"
    return "any"


def parse_buffer_prefixes(buffer: str) -> set[str]:
    """Return the set of prefix names declared with PREFIX in *buffer*."""
    return {m.group(1) for m in _PREFIX_DECL_RE.finditer(buffer)}


def qname_candidates(idx: UriIndex, prefix: str, filter_text: str, context: str) -> list[str]:
    """Return filtered, alphabetically-sorted local names for *prefix*.

    *context* is ``"class"`` or ``"any"``.  When ``"class"``, only names from
    the ``classes`` bucket are returned.  Filter is applied case-insensitively
    as a prefix match.
    """
    bucket_key = "classes" if context == "class" else "all"
    names = idx.get(prefix, {}).get(bucket_key, [])
    f = filter_text.lower()
    return [n for n in names if n.lower().startswith(f)]


def extract_query_variables(buffer: str) -> list[str]:
    """Return a sorted, deduplicated list of ``?variable`` names in *buffer*."""
    return sorted(set(re.findall(r"\?([A-Za-z_][A-Za-z0-9_]*)", buffer)))


def extract_result_uris(rows: list[list[str]]) -> set[str]:
    """Collect every URI-like value from SELECT result rows.

    Scans all columns of all rows; any cell that starts with ``http://`` or
    ``https://`` is treated as a URI.  Returns an empty set for literal-only
    or empty result sets.
    """
    uris: set[str] = set()
    for row in rows:
        for cell in row:
            if cell.startswith("http://") or cell.startswith("https://"):
                uris.add(cell)
    return uris


# ── Internal helpers ──────────────────────────────────────────────────────────


def _fmt_value(val: object) -> str:
    if val is None:
        return ""
    if isinstance(val, rdflib.URIRef):
        return str(val)
    if isinstance(val, rdflib.Literal):
        lang = getattr(val, "language", None)
        return f"{val}@{lang}" if lang else str(val)
    return str(val)


def _detect_format(path: Path) -> str:
    return {
        ".ttl": "turtle",
        ".n3": "n3",
        ".jsonld": "json-ld",
        ".rdf": "xml",
        ".owl": "xml",
    }.get(path.suffix.lower(), "turtle")


def _detect_query_type(sparql_text: str) -> str:
    m = re.search(r"\b(SELECT|ASK|CONSTRUCT|DESCRIBE)\b", sparql_text, re.IGNORECASE)
    return m.group(1).upper() if m else "SELECT"
