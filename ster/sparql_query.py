# ── Public data types ─────────────────────────────────────────────────────────


@dataclass
class QueryResult:
    """Normalised result from any SPARQL query type."""

    columns: list[str]
    rows: list[list[str]]  # every cell is a plain string
    error: str = ""
    query_type: str = "SELECT"  # SELECT | ASK | CONSTRUCT | DESCRIBE


@dataclass
class PresetQuery:
    label: str
    description: str
    sparql: str


