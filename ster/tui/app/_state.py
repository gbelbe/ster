"""Static-typing surface shared by every mixin: declares every attribute and
method ``OntologyApp`` (see ``__init__.py``) ends up with, so mypy can check
cross-mixin ``self.foo()`` calls inside one mixin's methods even though that
mixin doesn't itself define ``foo`` — some sibling mixin does, once they're
all composed into the real ``OntologyApp`` class.

This is a typing-only construct, generated from (and kept behaviour-identical
to) the original monolithic class's signatures and instance attributes. The
``TYPE_CHECKING`` branch is what mypy sees; the runtime branch is a bare,
empty class that changes nothing about any mixin's actual behaviour or MRO.
Deliberately *not* built by inheriting the real mixin classes: that would
make ``_AppState`` depend on every mixin while every mixin depends on
``_AppState`` — a genuine circular class hierarchy, not just a mypy
processing-order issue. Attributes textual's own ``App`` already provides
(``theme``, ``title``, ``sub_title``, …) are intentionally left out — they
come free from the ``App`` base below.
"""

